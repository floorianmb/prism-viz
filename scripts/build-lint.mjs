// Bundles src/lintCli.ts (offline check of viz blocks, no Obsidian needed) into
// scripts/prism-lint.mjs, which prism-render.mjs --lint imports. Run by `npm run build`.
import esbuild from "esbuild";
import fs from "fs";
import path from "path";

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
// src/libs.ts embeds the library sources, which the check does not need.
const noLibs = {
	name: "no-libs",
	setup(build) {
		build.onResolve({ filter: /^libtext:/ }, (args) => ({ path: args.path, namespace: "no-libs" }));
		build.onLoad({ filter: /.*/, namespace: "no-libs" }, () => ({ contents: 'export default "";', loader: "js" }));
	},
};
const out = await esbuild.build({
	entryPoints: [path.join(root, "src/lintCli.ts")],
	bundle: true,
	write: false,
	format: "esm",
	platform: "node",
	target: "node18",
	minify: true,
	legalComments: "none",
	logLevel: "error",
	external: ["obsidian"],
	plugins: [noLibs],
});
// Bundled CommonJS dependencies (js-yaml, acorn) may call require() of node builtins.
const banner = 'import { createRequire as __cr } from "module"; const require = __cr(import.meta.url);\n';
fs.writeFileSync(path.join(root, "scripts", "prism-lint.mjs"), "// Generated by `npm run build` from src/lintCli.ts – do not edit.\n" + banner + out.outputFiles[0].text);
console.log("scripts/prism-lint.mjs written");
